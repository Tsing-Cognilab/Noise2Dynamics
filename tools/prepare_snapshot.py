#!/usr/bin/env python3
"""Prepare a CVM-only snapshot; never modify the mixed source project."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

CODE = ('task_restore_v1', 'task_restore_method_v1', 'task_restore_repeat_v1',
        'task_restore_confirm_v1', 'task_restore_external_v1', 'task_restore_video_hd_v1')
OUTPUT = ('task_restore_v1', 'task_restore_method_v1', 'task_restore_repeat_v1',
          'task_restore_confirm_v1', 'task_restore_external_v1', 'cvm_video_hd_v1')
ROOTS = CODE + tuple('outputs/' + x for x in OUTPUT)
MODEL = {'.pt', '.pth', '.ckpt'}
DATA = {'.h5', '.hdf5', '.npz', '.npy'}
RESOURCE = {'.gz', '.zip', '.zst', '.tar'}
DRAFTS = {'task_restore_v1/CVM2027_PLAN_20261003.md',
          'task_restore_method_v1/N2D_CVM2027主线计划.md'}
SECRET = re.compile(rb'-----BEGIN (?:OPENSSH|RSA|EC|DSA|ENCRYPTED)? ?PRIVATE KEY-----|'
                    rb'\bgh[pousr]_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}\b|'
                    rb'\bAKIA[A-Z0-9]{16}\b')
PART_SIZE = 128 * 1024 * 1024


def log(msg):
    print(time.strftime('[%Y-%m-%d %H:%M:%S] ') + msg, flush=True)


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(4 * 1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    tmp.replace(path)


def write_jsonl(path, records):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in records), encoding='utf-8')
    tmp.replace(path)


def excluded(rel):
    if any(p in {'.git', '__pycache__', '.pytest_cache'} for p in rel.parts):
        return 'Git history or generated cache'
    if rel.suffix in {'.pyc', '.pyo', '.lock', '.partial', '.tmp'}:
        return 'Incomplete download, generated bytecode or runtime lock'
    if rel.as_posix() in DRAFTS:
        return 'Duplicate early planning draft; stage protocols retained'
    return None


def kind(path, size):
    if path.suffix in MODEL:
        return 'models'
    if path.suffix in DATA:
        return 'datasets'
    if path.suffix in RESOURCE or size >= 50 * 1024 * 1024:
        return 'resources'
    return 'git'


def pack(root, group, entries):
    folder = root / 'artifacts'
    folder.mkdir(exist_ok=True)
    dest = folder / ('cvm-' + group + '.tar.zst')
    marker = dest.with_name(dest.name + '.verified.json')
    fingerprint = hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()
    valid = False
    if marker.exists() and dest.exists():
        old = json.loads(marker.read_text())
        valid = old['fingerprint'] == fingerprint and old['sha256'] == sha(dest)
    if not valid:
        filelist = folder / (group + '.filelist')
        filelist.write_bytes(b''.join(e['path'].encode() + b'\0' for e in entries))
        tmp = dest.with_name(dest.name + '.partial')
        log('Packing ' + group + ' with zstd, two CPU threads')
        with tmp.open('wb') as output:
            tar = subprocess.Popen(['tar', '-C', str(root), '--no-recursion', '--null', '--verbatim-files-from',
                                    '-T', str(filelist), '-cf', '-'], stdout=subprocess.PIPE)
            zstd = subprocess.Popen(['zstd', '-q', '-T2', '-3', '-c'], stdin=tar.stdout, stdout=output)
            tar.stdout.close()
            if zstd.wait() != 0 or tar.wait() != 0:
                raise RuntimeError('Packing failed; source snapshot remains intact')
        subprocess.run(['zstd', '-q', '-t', str(tmp)], check=True)
        tmp.replace(dest)
        write_json(marker, {'fingerprint': fingerprint, 'sha256': sha(dest)})
    digest = sha(dest)
    parts = []
    if dest.stat().st_size <= PART_SIZE:
        parts.append({'name': dest.name, 'bytes': dest.stat().st_size, 'sha256': digest})
    else:
        with dest.open('rb') as f:
            index = 1
            while True:
                block = f.read(PART_SIZE)
                if not block:
                    break
                part = dest.with_name(dest.name + '.part' + str(index).zfill(3))
                h = hashlib.sha256(block).hexdigest()
                if not part.exists() or part.stat().st_size != len(block) or sha(part) != h:
                    tmp = part.with_name(part.name + '.partial')
                    tmp.write_bytes(block)
                    tmp.replace(part)
                parts.append({'name': part.name, 'bytes': len(block), 'sha256': h})
                index += 1
    return {'name': dest.name, 'bytes': dest.stat().st_size, 'sha256': digest, 'parts': parts}


def prepare(source, target, templates):
    source, target, templates = source.resolve(), target.resolve(), templates.resolve()
    if target == source or source in target.parents or target in source.parents:
        raise RuntimeError('Snapshot must be separate from the original project')
    if any(not (source / p).is_dir() for p in ROOTS):
        raise RuntimeError('Missing a required CVM source/output directory')
    marker = target / '.cvm-snapshot.json'
    if target.exists() and any(target.iterdir()) and not marker.is_file():
        raise RuntimeError('Refusing an existing, unmarked destination')
    target.mkdir(parents=True, exist_ok=True)
    if marker.exists() and json.loads(marker.read_text())['source'] != str(source):
        raise RuntimeError('Snapshot belongs to a different source')
    write_json(marker, {'source': str(source), 'format': 1})
    records, exclusions = [], []
    for top in ROOTS:
        for dirpath, directories, filenames in os.walk(source / top, followlinks=False):
            for name in list(directories):
                p = Path(dirpath) / name
                rel = p.relative_to(source)
                reason = excluded(rel) or ('Symlink directory' if p.is_symlink() else None)
                if reason:
                    directories.remove(name)
                    exclusions.append({'path': rel.as_posix(), 'reason': reason})
            for name in sorted(filenames):
                src = Path(dirpath) / name
                rel = src.relative_to(source)
                reason = excluded(rel) or ('Symlink file' if src.is_symlink() else None)
                if reason:
                    exclusions.append({'path': rel.as_posix(), 'reason': reason, 'bytes': src.lstat().st_size})
                    continue
                size = src.stat().st_size
                category = kind(src, size)
                if category == 'git' and size <= 5 * 1024 * 1024:
                    if SECRET.search(src.read_bytes()):
                        raise RuntimeError('Credential-like content: ' + rel.as_posix())
                before = src.stat()
                h = sha(src)
                dst = target / rel
                if dst.exists():
                    if dst.is_symlink() or sha(dst) != h:
                        raise RuntimeError('Existing snapshot file differs: ' + rel.as_posix())
                else:
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    tmp = dst.with_name(dst.name + '.partial')
                    shutil.copy2(src, tmp)
                    if sha(tmp) != h:
                        raise RuntimeError('Copy checksum mismatch: ' + rel.as_posix())
                    tmp.replace(dst)
                after = src.stat()
                if before.st_size != after.st_size or before.st_mtime_ns != after.st_mtime_ns:
                    raise RuntimeError('Source changed during snapshot: ' + rel.as_posix())
                records.append({'path': rel.as_posix(), 'bytes': size, 'sha256': h, 'kind': category})
        log('Copied and verified ' + top)
    records.sort(key=lambda x: x['path'])
    write_jsonl(target / 'manifests/files.jsonl', records)
    assets = [r for r in records if r['kind'] != 'git']
    write_jsonl(target / 'manifests/binary_assets.jsonl', assets)
    write_jsonl(target / 'manifests/excluded.jsonl', exclusions)
    generated = {'CVM_REPOSITORY_README.md': 'README.md', 'CVM_GITHUB_上传与恢复说明.md': 'docs/上传与恢复说明.md',
                 'restore_cvm_assets.py': 'tools/restore_assets.py', 'publish_cvm_repository.py': 'tools/publish.py',
                 'bootstrap_cvm_gh.py': 'tools/bootstrap_gh.py', 'prepare_cvm_repository.py': 'tools/prepare_snapshot.py'}
    for name, rel in generated.items():
        dst = target / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(templates / name, dst)
    ignores = ['.git/', '__pycache__/', '*.pyc', '*.lock', '*.partial', '*.tmp',
               '/artifacts/', '/tools/.runtime/', '/.cvm-snapshot.json', '/UPLOAD_COMPLETE.json',
               '/upload.log', '/upload-progress.json', '*.pt', '*.pth', '*.ckpt', '*.h5', '*.hdf5',
               '*.npz', '*.npy', '*.tar', '*.gz', '*.zip', '*.zst']
    ignores += ['/' + r['path'] for r in assets if Path(r['path']).suffix not in MODEL | DATA | RESOURCE]
    (target / '.gitignore').write_text('\n'.join(ignores) + '\n', encoding='utf-8')
    (target / '.gitattributes').write_text('* -text\n', encoding='utf-8')
    env = {'image': 'noise2dynamics:taskrestore-v1', 'policy_python': '/opt/taskrestore/bin/python',
           'torch': '2.5.1+cu124', 'robomimic': '0.2.0', 'mujoco': '2.1', 'rendering': 'CPU OSMesa',
           'robosuite_commit': '277ab9588ad7a4f4b55cf75508b44aa67ec171f0',
           'dockerfile_base': 'noise2dynamics:franka-v1', 'standalone_docker_build': False}
    try:
        env['image_id'] = subprocess.check_output(['docker', 'image', 'inspect', '--format', '{{.Id}}', env['image']], text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        env['image_id'] = None
    write_json(target / 'docs/ENVIRONMENT.json', env)
    summary = {'source': str(source), 'target': str(target), 'roots': list(ROOTS), 'format': 1,
               'files': len(records), 'bytes': sum(r['bytes'] for r in records),
               'groups': {k: {'files': sum(r['kind'] == k for r in records),
                              'bytes': sum(r['bytes'] for r in records if r['kind'] == k)}
                          for k in ('git', 'models', 'datasets', 'resources')},
               'excluded_entries': len(exclusions), 'training_seeds': [3072, 3073, 3074],
               'uploaded': False}
    write_json(target / 'manifests/PREPARATION.json', summary)
    packages = [pack(target, k, [r for r in records if r['kind'] == k])
                for k in ('datasets', 'models', 'resources') if any(r['kind'] == k for r in records)]
    release = {'format': 1, 'repository': 'Audience2Li/Noise2Dynamics',
               'tag': 'cvm-assets-20261013', 'packages': packages}
    write_json(target / 'artifacts/release-manifest.json', release)
    write_json(target / 'manifests/release-manifest.json', release)
    lines = [p['sha256'] + '  ' + p['name'] for package in packages for p in package['parts']]
    (target / 'artifacts/SHA256SUMS').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    if not (target / '.git').exists():
        subprocess.run(['git', 'init', '-b', 'main', str(target)], check=True)
    subprocess.run(['git', '-C', str(target), 'config', 'core.autocrlf', 'false'], check=True)
    subprocess.run(['git', '-C', str(target), 'add', '--all'], check=True)
    tracked = subprocess.check_output(['git', '-C', str(target), 'ls-files', '-z']).split(b'\0')
    for name in filter(None, tracked):
        path = target / os.fsdecode(name)
        if path.stat().st_size >= 50 * 1024 * 1024 or path.suffix in MODEL | DATA | RESOURCE:
            raise RuntimeError('Unexpected large/binary tracked file: ' + os.fsdecode(name))
    summary['release_upload_bytes'] = sum(p['bytes'] for package in packages for p in package['parts'])
    summary['release_upload_files'] = sum(len(package['parts']) for package in packages) + 2
    summary['git_tracked_files'] = len(list(filter(None, tracked)))
    write_json(target / 'manifests/PREPARATION.json', summary)
    subprocess.run(['git', '-C', str(target), 'add', 'manifests/PREPARATION.json'], check=True)
    log('READY ' + json.dumps(summary, ensure_ascii=False))
    return summary


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=Path('/data/lizhenhao/lizhenhao/n2d_dreamerv3'))
    parser.add_argument('--target', type=Path, default=Path('/data/lizhenhao/lizhenhao/Noise2Dynamics_CVM'))
    parser.add_argument('--templates', type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    try:
        prepare(args.source, args.target, args.templates)
    except Exception as exc:
        log('FAILED: ' + str(exc))
        sys.exit(1)
